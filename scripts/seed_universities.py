async def seed() -> None:
    async with async_session() as session:
        regions = {r.name: r for r in (await session.execute(select(Region))).scalars().all()}
        existing = {u.name.lower(): u for u in (await session.execute(select(University))).scalars().all()}

        added = 0
        linked = 0
        for region_name, names in UNIVERSITIES_BY_REGION.items():
            region = regions.get(region_name)
            if region is None:
                print(f"Регион «{region_name}» не найден в этой базе — пропускаю его список ({len(names)} вузов).")
                continue
            for name in names:
                key = name.lower()
                university = existing.get(key)
                if university is None:
                    university = University(name=name, region_id=region.id)
                    session.add(university)
                    existing[key] = university
                    added += 1
                elif university.region_id is None:
                    university.region_id = region.id
                    linked += 1
        await session.commit()
    print(f"Добавлено новых вузов: {added}; проставлен регион уже существовавшим записям: {linked}")


if __name__ == "__main__":
    asyncio.run(seed())

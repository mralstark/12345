"""Заполняет перечень проверки текстов согласованными словами.

    python -m scripts.seed_moderation_words

Безопасен для повторов: что уже есть, не добавляется заново. Слова, добавленные
руками, не трогает — скрипт только досыпает недостающее из согласованного
списка.

Перечень живёт в базе, чтобы его можно было менять без выкладки. Этот скрипт —
только начальное наполнение.
"""

import asyncio

from sqlalchemy import select

from database.db import async_session, init_db
from database.models import ModerationWord
from services.moderation import KIND_ALLOW, KIND_BLOCK, KIND_WARN, normalize

# Мат: публиковать нельзя ни в каком контексте. Корней немного — русский мат
# на них и стоит, а окончания ловятся сами (сравнение идёт по началу слова).
# Приставочные формы: сравнение идёт по НАЧАЛУ слова, поэтому корень в
# середине слова так не поймать — «долбоёб» проходил свободно, пока этих
# строк не было. Собираем механически, чтобы ничего не забыть.
_ЕБ = [prefix + "еб" for prefix in
       ("за", "на", "вы", "у", "по", "при", "отъ", "до", "пере",
        "разъ", "съ", "объ", "изъ", "долбо")]

BLOCK = [
    # Собственно мат.
    "хуй", "пизд", "еб", "бля", "муд", "манда",
    *_ЕБ,
    # Грубое и нецензурное, хоть и не мат в строгом смысле.
    "хер", "говн", "дерьм", "жоп", "срат", "ссат", "залуп",
    "пидор", "пидар", "гандон", "шлюх", "сука", "суки", "сучк", "сукин", "чмо",
]

# Спорное: пост выходит, автор видит вопрос, руководству уходит уведомление.
# Слова про нацизм тут намеренно широко — предупреждение ничего не ломает, а
# Братство академическое: посты про историю двадцатого века обязаны выходить.
WARN = [
    # Брань, но не мат — по решению руководства только предупреждаем.
    "сволоч", "ублюд", "мраз", "тварь", "урод", "придур",
    "гитлер", "нацизм", "нацист", "фашизм", "фашист",
    "свастик", "рейх", "холокост", "зиг хайль", "майн кампф",
]

# Исключения: обычные слова, начинающиеся так же, как корень из списка.
# Проверено на настоящих словах — без этого списка фильтр заблокировал бы
# пост со словом «мудрость» и не пропустил бы «мандат».
ALLOW = [
    "мудр",       # мудрость, мудрый, мудрец
    "муде",       # мудрёный
    "мандат",     # мандат, мандаты
    "мандарин",   # мандарин
    "бляха", "бляш",
    "херсон",     # город и всё от него
    "херувим",    # у Братства вполне может встретиться
    "сукно", "сукн", "сукач",   # сукно, суконный, фамилия Сукачёв
    "чмок",       # чмокнуть
    "рейхстаг",   # обычное историческое слово
]


async def seed() -> None:
    # Таблицу создаёт запуск приложения; скрипт могут позвать и раньше, на
    # свежей базе — тогда её просто не будет. create_all только досоздаёт
    # недостающее, существующего не трогает.
    await init_db()

    pairs = (
        [(w, KIND_BLOCK) for w in BLOCK]
        + [(w, KIND_WARN) for w in WARN]
        + [(w, KIND_ALLOW) for w in ALLOW]
    )

    async with async_session() as session:
        existing = {
            (row.root, row.kind)
            for row in (await session.execute(select(ModerationWord))).scalars().all()
        }
        added = 0
        for word, kind in pairs:
            root = normalize(word).strip()
            if not root or (root, kind) in existing:
                continue
            session.add(ModerationWord(root=root, kind=kind))
            added += 1
        await session.commit()

    print(f"Добавлено слов: {added}")
    print(f"Всего в перечне: {len(existing) + added}")
    if not added:
        print("Перечень уже заполнен — ничего не менялось.")


if __name__ == "__main__":
    asyncio.run(seed())
